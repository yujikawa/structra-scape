export function translateUI(value, language = 'ja') {
  if (language !== 'en') return value;
  const trimmed = value.trim();
  if (Object.hasOwn(englishUI, trimmed)) return value.replace(trimmed, englishUI[trimmed]);
  const rules = [
    [/^使われている作業 · (\d+)件$/, (_, n) => `Used in ${n} steps`],
    [/^(\d+)件$/, (_, n) => `${n} items`],
    [/^(\d+)個の作業 · (\d+)本の流れ$/, (_, a, b) => `${a} steps · ${b} flows`],
    [/^(.+) · (\d+)つの用語・関係に、確認が必要な項目があります。$/, (_, name, n) => `${name} · ${n} terms / relationships need review.`],
    [/^(.+) · (モデルに確認が必要な項目があります。|記録上の未確認事項はありません。)$/, (_, name, text) => `${name} · ${englishUI[text]}`],
    [/^(未決定|不足|未合意|不整合|データ対応) (\d+)$/, (_, label, n) => `${englishUI[label]} ${n}`],
    [/^データとの対応 · (確認済み|対応案・未確認|未整理)$/, (_, label) => `Data mapping · ${englishUI[label]}`],
    [/^相談したいこと：([\s\S]*)$/, (_, text) => `Open question: ${text}`],
    [/^(作業|開始|終了|分岐（一つ選ぶ）|並行開始|合流（すべて待つ）) · ([\s\S]*)$/, (_, kind, owner) => `${englishUI[kind]} · ${owner}`],
    [/^([\s\S]*) · (作成する|参照する|更新する|参加する)$/, (_, name, role) => `${name} · ${englishUI[role]}`],
    [/^([\s\S]*)の一種$/, (_, name) => `A kind of ${name}`],
    [/^([\s\S]*)は([\s\S]*)の一種です。$/, (_, subject, parent) => `${subject} is a kind of ${parent}.`],
    [/^([\s\S]*)から([\s\S]*)への「([\s\S]*)」という関係です。$/, (_, source, target, relation) => `Relationship “${relation}” from ${source} to ${target}.`],
    [/^([\s\S]*)の分類条件：([\s\S]*)。相手の種類は([\s\S]*)です。$/, (_, subject, rule, target) => `Classification rule for ${subject}: ${rule}. Target type: ${target}.`],
    [/^「([\s\S]*)」の条件：「([\s\S]*)」でつながる「([\s\S]*)」が、少なくとも1つある。$/, (_, subject, property, target) => `Rule for “${subject}”: at least one “${property}” relationship to “${target}”.`],
    [/^「([\s\S]*)」の条件：「([\s\S]*)」の相手はすべて「([\s\S]*)」。相手がいない場合も、この条件は満たす。$/, (_, subject, property, target) => `Rule for “${subject}”: all “${property}” targets are “${target}”. This also holds when there are no targets.`],
    [/^「([\s\S]*)」の条件：「([\s\S]*)」でつながる相手は、(最低|最大|ちょうど)(\d+)。$/, (_, subject, property, bound, count) => `Rule for “${subject}”: ${({'最低':'at least','最大':'at most','ちょうど':'exactly'})[bound]} ${count} “${property}” targets.`],
    [/^判定が未決定：([\s\S]*)$/, (_, text) => `Undecided case: ${text}`],
    [/^「([\s\S]*)」の個数条件を同時に満たせません。$/, (_, name) => `The cardinality constraints for “${name}” cannot all be satisfied.`],
    [/^同じことばから、同じ意味を思い浮かべられますか？　(\d+)個のことば · (\d+)個が合意済み$/, (_, a, b) => `Do these terms mean the same thing to everyone? ${a} terms · ${b} agreed`],
  ];
  for (const [pattern, replacement] of rules) if (pattern.test(trimmed)) return value.replace(trimmed, trimmed.replace(pattern, replacement));
  return value;
}
